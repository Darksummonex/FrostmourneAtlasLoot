local function AddJusticeTrinket()
    local rows=AtlasLoot_Data and AtlasLoot_Data.EmblemofHeroism2
    if not rows then return end
    local used={}
    for _,row in ipairs(rows) do
        if tonumber(row[2])==37111 then row[3]="INV_Misc_Orb_03"; return end
        used[row[1]]=true
    end
    for position=24,30 do
        if not used[position] then
            rows[#rows+1]={position,37111,"INV_Misc_Orb_03","=q3=Soul Preserver","=ds=#s14#","1650 #eofheroism#"}
            return
        end
    end
end
