        if first then
            local root=item[1]:gsub("%d+$","")
            local page=1
            local found=false
            while AtlasLoot_Data[root..page] do
                for _,row in ipairs(AtlasLoot_Data[root..page]) do
                    if tonumber(row[2])==item[2] or tonumber(row[3])==item[2] then found=true end
                end
                page=page+1
            end
