-- Read only tooltips the player opens; no requests, timer, inventory or vendor scan.
local function LearnLegendaryClass(tooltip)
    local _,link=tooltip:GetItem()
    local id=link and tonumber(link:match("item:(%d+)"))
    if not id or not legendaryTypes[id] or not GetItemInfo(id) then return end
    local template=ITEM_CLASSES_ALLOWED or "Classes: %s"
    local prefix=template:match("^(.-)%%s") or "Classes: "
    local classText
    for line=1,tooltip:NumLines() do
        local text=_G[tooltip:GetName().."TextLeft"..line]
        text=text and text:GetText()
        if text then
            text=text:gsub("|c%x%x%x%x%x%x%x%x",""):gsub("|r","")
            if text:sub(1,#prefix)==prefix then classText=text:sub(#prefix+1); break end
        end
    end
    classText=classText or "No class restriction"
    local labels=LegendaryClassLabels()
    if labels[id]==classText then return end
    labels[id]=classText
    ns.RegisterCustomLegendaries()
    -- Update the visible row without reopening the tooltip or loot page.
    local rows=AtlasLoot_Data.FMCustomLegendaries1
    local refresh=AtlasLootItemsFrame and AtlasLootItemsFrame.refresh
    if rows and refresh and refresh[1]=="FMCustomLegendaries1" then
        for _,row in ipairs(rows) do
            local extra=_G["AtlasLootItem_"..row[1].."_Extra"]
            if extra then extra:SetText(AtlasLoot_FixText(row[5])) end
        end
    end
end
