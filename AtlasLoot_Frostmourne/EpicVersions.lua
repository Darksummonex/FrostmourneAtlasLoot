local layouts={}
local function Apply()
    if not AtlasLoot_Data then return end
    for source,items in pairs(matches) do
        local original=AtlasLoot_Data[source]
        if original and not layouts[source] then
            local columns={{},{}}
            local positions={}
            local sorted={}
            for _,row in ipairs(original) do sorted[#sorted+1]=row end
            table.sort(sorted,function(a,b) return a[1]<b[1] end)
            for _,row in ipairs(sorted) do
                local column=row[1]<=15 and 1 or 2
                columns[column][#columns[column]+1]=row
                if tonumber(row[2]) then positions[tonumber(row[2])]={column=column,position=row[1]} end
            end
            local epics={{},{}}
            for _,item in ipairs(items) do
                local origin=positions[item[5]]
                if origin and item[7]==1 then
                    epics[origin.column][#epics[origin.column]+1]={item=item,position=origin.position}
                end
            end
            for column=1,2 do
                table.sort(epics[column],function(a,b)
                    if a.position~=b.position then return a.position<b.position end
                    return a.item[1]<b.item[1]
                end)
                if #epics[column]>0 then
                    columns[column][#columns[column]+1]={0,0,"INV_Box_01","=q4=Epic versions",""}
                    for _,entry in ipairs(epics[column]) do
                        local item=entry.item
                        columns[column][#columns[column]+1]={0,tostring(item[1]),item[4],"=q4="..item[2],item[3]}
                    end
                end
            end
            layouts[source]=columns
        end
    end
end
ns.ApplyDungeonEpicVersions=Apply
ns.DungeonEpicLayouts=layouts

-- Keep long lists in the boss view, with both difficulty columns scrolling together.
local scroll,child,buttons,current
local verify=CreateFrame("Frame")
local query=CreateFrame("GameTooltip","FMEpicVerifyTooltip",UIParent,"GameTooltipTemplate")
local waiting,elapsed={},0
local ShowInline
local function QueueVerification(source)
    waiting={}; elapsed=0
    for _,item in ipairs(matches[source] or {}) do
        if item[7]==0 then waiting[item[5]]=true end
    end
    verify:SetScript("OnUpdate",next(waiting) and function(self,dt)
        elapsed=elapsed+dt
        if elapsed<0.1 then return end
        elapsed=0
        local changed=false
        local requested=false
        for id,state in pairs(waiting) do
            local name,link,quality,level=GetItemInfo(id)
            if name then
                for _,item in ipairs(matches[source]) do
                    if item[5]==id then item[7]=(name==item[2] and level==item[6]) and 1 or -1 end
                end
                waiting[id]=nil; changed=true
            elseif state==true and not requested then
                requested=true; waiting[id]=GetTime()
                query:SetOwner(UIParent,"ANCHOR_NONE")
                pcall(query.SetHyperlink,query,"item:"..id..":0:0:0:0:0:0:0"); query:Hide()
            elseif type(state)=="number" and GetTime()-state>5 then waiting[id]=nil end
        end
        if changed then layouts[source]=nil; Apply(); ShowInline(source,true) end
        if not next(waiting) then self:SetScript("OnUpdate",nil) end
    end or nil)
end
local function Wheel(_,delta)
    if scroll then
        local maximum=math.max(0,child:GetHeight()-scroll:GetHeight())
        scroll:SetVerticalScroll(math.max(0,math.min(maximum,scroll:GetVerticalScroll()-delta*56)))
    end
end
local function InitView()
    if scroll then return end
    buttons={}
    scroll=CreateFrame("ScrollFrame","FMDungeonEpicScroll",AtlasLootItemsFrame)
    scroll:SetPoint("TOPLEFT",AtlasLootItemsFrame,"TOPLEFT",25,-35)
    scroll:SetWidth(472); scroll:SetHeight(420)
    child=CreateFrame("Frame",nil,scroll)
    child:SetWidth(472); child:SetHeight(420)
    scroll:SetScrollChild(child)
    scroll:EnableMouseWheel(true); scroll:SetScript("OnMouseWheel",Wheel)
    local bar=CreateFrame("Slider","FMDungeonEpicScrollbar",scroll,"UIPanelScrollBarTemplate")
    bar:SetPoint("TOPLEFT",scroll,"TOPRIGHT",0,-16)
    bar:SetPoint("BOTTOMLEFT",scroll,"BOTTOMRIGHT",0,16)
    bar:SetMinMaxValues(0,0); bar:SetValueStep(28); bar:SetValue(0)
    bar:SetScript("OnValueChanged",function(self,value) scroll:SetVerticalScroll(value) end)
    scroll:SetScript("OnVerticalScroll",function(self,value) bar:SetValue(value) end)
    scroll.bar=bar
end
ShowInline=function(dataID,refresh)
    if not refresh then verify:SetScript("OnUpdate",nil); waiting={} end
    if scroll then scroll:Hide() end
    local columns=layouts[dataID]
    if not columns then current=nil; return end
    InitView()
    for i=1,30 do local button=_G["AtlasLootItem_"..i]; if button then button:Hide() end end
    for _,button in ipairs(buttons) do button:Hide() end
    local count=0
    local rows=math.max(#columns[1],#columns[2])
    child:SetHeight(math.max(420,rows*28))
    scroll.bar:SetMinMaxValues(0,math.max(0,rows*28-420))
    if current~=dataID then scroll:SetVerticalScroll(0) end
    current=dataID
    for column=1,2 do
        for index,row in ipairs(columns[column]) do
            count=count+1
            local button=buttons[count]
            if not button then
                -- AtlasLoot tooltip and click handlers use AtlasLootItem_<ID> names.
                local id=30+count
                button=CreateFrame("Button","AtlasLootItem_"..id,child,"AtlasLootItem_Template")
                button:SetID(id); buttons[count]=button
                button:EnableMouseWheel(true); button:SetScript("OnMouseWheel",Wheel)
            end
            local name=button:GetName()
            local texture=row[3]
            if not texture or texture=="" then texture=GetItemIcon(row[2]) end
            if type(texture)=="string" and not texture:find("\\",1,true) then texture="Interface\\Icons\\"..texture end
            _G[name.."_Icon"]:SetTexture(texture or "Interface\\Icons\\INV_Misc_QuestionMark")
            _G[name.."_Name"]:SetText(AtlasLoot_FixText(row[4] or ""))
            _G[name.."_Extra"]:SetText(AtlasLoot_FixText(row[5] or ""))
            _G[name.."_Extra"]:Show()
            _G[name.."_Unsafe"]:Hide()
            button.itemID=row[2]; button.storeID=row[2]; button.dressingroomID=row[2]
            button.spellitemID=0; button.itemTexture=row[3]; button.desc=row[5]
            button.price=row[6]; button.droprate=row[7]; button.sourcePage=nil
            button.name=AtlasLoot_FixText(row[4] or ""); button.extra=AtlasLoot_FixText(row[5] or "")
            button.iteminfo={idcore=row[2],icontexture=texture}; button.i=1
            button:ClearAllPoints(); button:SetPoint("TOPLEFT",child,"TOPLEFT",(column-1)*236,-(index-1)*28)
            button:Show()
        end
    end
    if rows>15 then scroll.bar:Show() else scroll.bar:Hide() end
    scroll:Show()
    if not refresh then QueueVerification(dataID) end
end
